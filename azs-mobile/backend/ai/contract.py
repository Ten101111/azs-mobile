def system_prompt() -> str:
    schema = CATALOG.description or SCHEMA
    examples = CATALOG.examples or EXAMPLES
    shots = "\n\n".join(
        f"Вопрос: {question}\nSQL:\n{sql}" for question, sql in examples
    )
    today = date.today().isoformat()
    return (
        "Ты переводишь вопросы о сети АЗС в SQL-запросы к витрине данных.\n"
        f"Сегодня {today}. «Сегодня», «на сегодняшний день», «текущий месяц» и\n"
        "«с начала месяца» означают период с первого числа текущего месяца\n"
        "по сегодняшнее число включительно.\n\n"
        f"{schema}\n{rules()}\n{GLOSSARY}\n"
        f"Примеры:\n\n{shots}\n"
    )


def prompt_version() -> str:
    """Короткая метка версии системной инструкции.

    Считается из самого текста, а не ведётся руками: иначе метка рано или
    поздно разойдётся с инструкцией, и срез «до и после смены версии»
    (БТ-КК7) будет врать. Дата из подсказки исключается — она меняется
    каждый день и к версии инструкции отношения не имеет.
    """
    body = "\n".join(part for part in (
        (CATALOG.description or SCHEMA), rules(), GLOSSARY, NARRATION_SYSTEM,
    ))
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:8]


def user_prompt(question: str, context: str = "") -> str:
    # context — то, что контур уже определил сам (например, кто из людей в вопросе
    # РУ, а кто ТМ); модель берёт это как данность, а не угадывает.
    head = f"{context.strip()}\n\n" if context and context.strip() else ""
    return f"{head}Вопрос: {question.strip()}\nSQL:"


NARRATION_SYSTEM = """\
Ты объясняешь результат аналитического запроса руководителю в нефтепродуктовой рознице.

Правила:
1. Пиши по-русски, 2-4 предложения, без заголовков и списков.
2. Используй только те числа, которые есть в данных. Ничего не досчитывай и не
   предполагай. Процентов и изменений, которых нет в таблице, не называй.
3. Начинай с прямого ответа на вопрос, а не с пересказа условия.
4. Числа приводи с разделением разрядов и с единицей измерения из названия колонки.
5. Если строк много, назови общую картину и один-два примечательных объекта.
6. Не рассуждай о причинах и не давай советов — только то, что видно в данных.
7. Не упоминай SQL, таблицы, запрос и то, как данные получены.
8. Термины и сокращения — из справочника проекта, он приведён ниже.
"""


# Справочник подставляется и в текстовый ответ: путаница УС и КС в нём заметнее,
# чем в SQL, потому что до пользователя доходит именно текст.
NARRATION_SYSTEM = NARRATION_SYSTEM + "\n" + GLOSSARY


def narration_prompt(question: str, scope: str, columns: list[str], rows: list) -> str:
    header = " | ".join(columns)
    body = "\n".join(
        " | ".join("—" if cell is None else str(cell) for cell in row) for row in rows
    )
    return (
        f"Вопрос: {question}\n"
        f"Область данных: {scope}\n\n"
        f"Результат:\n{header}\n{body}\n\n"
        "Ответь по правилам."
    )
