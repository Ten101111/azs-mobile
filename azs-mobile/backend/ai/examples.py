"""Примеры вопросов под орбом (ИИ-08): свои для каждой роли.

Пример — подсказка, а не право: область данных всё равно задаёт код
(`scope`), и вопрос с чужими объектами получит отказ. Поэтому примеры
составлены так, чтобы по ним всегда был ответ:

* только показатели, которые есть в витрине ОХД, — у каждого примера указан
  ключ показателя семантического слоя, тест сверяет его с поиском по слою;
* ничего из того, чего в витрине нет (трасса или город, персонал, тексты отзывов);
* без месяцев и годов — «в текущем месяце»: примеры не устаревают;
* роли с ограниченной областью спрашивают о своих объектах, без сети и чужих
  обществ; руководители сравниваются только с руководителями своего уровня.

Какие роли что видят — `backend/roles.py`; ИИ-диалог есть у администратора,
субадминистратора, АУП сети, АУП общества и руководителя управления. Для
остальных ролей набор нужен, когда администратор спрашивает «от имени» роли.
"""
from __future__ import annotations

from dataclasses import dataclass

from .. import roles


@dataclass(frozen=True)
class Example:
    hint: str    # подпись кнопки — коротко, до 24 знаков
    ask: str     # вопрос, который кладётся в поле (его можно поправить)
    metric: str  # ключ показателя в семантическом слое витрины — для проверки


NETWORK = (
    Example("План НТУ по обществам", "Выполнение плана выручки НТУ по обществам в текущем месяце",
            "plan_completion_ntu"),
    Example("Топливо к прошлому году",
            "Реализация топлива в тоннах по сети в текущем месяце к тому же периоду прошлого года", "fuel_weight"),
    Example("Конверсия по обществам", "Конверсия НТУ по обществам в текущем месяце к прошлому месяцу",
            "conversion_ntu"),
)

SOCIETY = (
    Example("Выполнение плана НТУ", "Выполнение плана выручки НТУ по нашему обществу в текущем месяце: факт, "
            "план на прошедшие дни, отставание", "plan_completion_ntu"),
    Example("Конверсия по управлениям", "Конверсия НТУ по руководителям управлений нашего общества "
            "в текущем месяце", "conversion_ntu"),
    Example("Отстающие от плана АЗС", "Выполнение плана выручки НТУ: пять АЗС общества с наибольшим "
            "отставанием в текущем месяце", "plan_completion_ntu"),
)

MANAGEMENT = (
    Example("Выполнение плана НТУ", "Выполнение плана выручки НТУ по моему управлению в текущем месяце: факт, "
            "план на прошедшие дни, отставание", "plan_completion_ntu"),
    Example("Конверсия по ТМ", "Конверсия НТУ по территориальным менеджерам моего управления в текущем месяце",
            "conversion_ntu"),
    Example("Отстающие от плана АЗС", "Выполнение плана выручки НТУ: пять моих АЗС с наибольшим отставанием "
            "в текущем месяце", "plan_completion_ntu"),
)

# ТМ, агент, управляющий АЗС и роль, которая ещё не назначена: «мои АЗС».
OWN = (
    Example("Выручка НТУ за месяц", "Выручка НТУ по моим АЗС в текущем месяце", "revenue_ntu"),
    Example("Выполнение плана НТУ", "Выполнение плана выручки НТУ по моим АЗС в текущем месяце: факт, "
            "план на прошедшие дни, отставание", "plan_completion_ntu"),
    Example("Конверсия по моим АЗС", "Конверсия НТУ по каждой моей АЗС в текущем месяце — таблицей",
            "conversion_ntu"),
)

BY_ROLE = {"aup_npo": SOCIETY, "regional_manager": MANAGEMENT}


def examples_of(role: str | None) -> tuple[Example, ...]:
    code = (role or "").strip()
    if code in BY_ROLE:
        return BY_ROLE[code]
    spec = roles.ROLES.get(code)
    return NETWORK if spec and spec.unrestricted else OWN


def for_role(role: str | None) -> list[dict]:
    """Примеры для экрана: подпись и вопрос."""
    return [{"hint": item.hint, "ask": item.ask} for item in examples_of(role)]


def by_role() -> dict[str, list[dict]]:
    """Все роли — для администратора, который спрашивает «от имени» другой роли."""
    return {code: for_role(code) for code in roles.ROLE_ORDER}
