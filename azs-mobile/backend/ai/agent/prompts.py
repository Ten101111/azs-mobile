def agent_user(question: str, plan_dict: dict, scope_label: str, today: str,
               data_range: dict | None, hits: dict | None, budget: dict) -> str:
    parts = [
        f"Сегодня {today}. Область данных пользователя: {scope_label}.",
    ]
    if data_range and data_range.get("min_date"):
        parts.append(f"Данные в витрине: с {data_range['min_date']} по {data_range['max_date']}"
                     + (f", объектов: {data_range.get('stations')}" if data_range.get("stations") else "") + ".")
    if hits:
        found = [f"{m['key']} = {m['expr']} ({m['unit']})" for m in hits.get("metrics", [])[:4]]
        dims = [f"{d['key']} → {d['table']}.{d['column']}" for d in hits.get("dimensions", [])[:4]]
        if found:
            parts.append("Подходящие показатели: " + "; ".join(found) + ".")
        if dims:
            parts.append("Подходящие измерения: " + "; ".join(dims) + ".")
        if hits.get("absent"):
            parts.append("В витрине нет: " + "; ".join(hits["absent"]) + " — учти в limitations.")
    parts.append(
        f"Задача: {question}\nТип: {plan_dict.get('taskType')}, глубина: {plan_dict.get('depth')}."
    )
    if plan_dict.get("steps"):
        parts.append("План:\n" + "\n".join(f"  {i + 1}. {s}" for i, s in enumerate(plan_dict["steps"])))
    parts.append(
        f"Бюджет: до {budget['sql']} запросов SQL, {budget['python']} вычислений Python, {budget['charts']} графиков."
        " Начинай с первого шага плана: вызови нужный инструмент."
    )
    return "\n".join(parts)


FINALIZE_SYSTEM = """\
Ты формулируешь итог анализа данных по сети АЗС для руководителя. У тебя есть только результаты запросов
и вычислений ниже — других чисел не существует. Отвечай строго одним JSON-объектом.

Правила:
1. Каждое число в тексте берётся из результатов как есть (можно округлить до разумной точности) с единицей
   измерения и периодом. Ничего не досчитывай и не предполагай.
2. headline — 1-2 предложения с самым важным результатом и ключевой цифрой. Для простого вопроса
   этого и пары пунктов happened достаточно; why/where/actions тогда пустые.
3. why — только факторы, подтверждённые результатами; формулируй «двигалось вместе с», а не «стало причиной».
4. actions — конкретное действие: что сделать, на каком объекте, какой показатель это двигает; если данных
   для рекомендации нет — оставь пустым, не сочиняй. При ссылке на методику — так и пиши «по методике».
5. limitations — чего в витрине нет, что не проверено, где сравнение условно (неполный месяц, обрезка).
   Если в задаче упоминалось отсутствующее в витрине — обязательно сюда.
6. Пиши по-русски, коротко, без SQL, без названий таблиц и без упоминания инструментов.
7. Чужие объекты не называй; свои — как в данных (номер/название).

Формат: {"headline": "...", "happened": ["..."], "why": ["..."], "where": ["..."], "actions": ["..."],
 "limitations": ["..."], "main_result": "rN"}
"""


def finalize_user(question: str, plan_dict: dict, evidence: str, notes: list[str]) -> str:
    text = [f"Задача: {question}", f"Тип: {plan_dict.get('taskType')}."]
    if plan_dict.get("missing"):
        text.append("В витрине отсутствует (обязательно в limitations): " + "; ".join(plan_dict["missing"]))
    if notes:
        text.append("Замечания проверок: " + " | ".join(notes[:8]))
    text.append("Результаты:\n" + evidence)
    text.append("JSON:")
    return "\n".join(text)


REPAIR_USER = """\
В твоём ответе есть числа, которых нет в результатах: {numbers}.
Перепиши тот же JSON, оставив только числа из результатов (округление допустимо), или убери фразы с ними.
JSON:"""


def prompt_version(semantic: Semantic) -> str:
    body = "\n".join((TRIAGE_SYSTEM, AGENT_RULES, FINALIZE_SYSTEM, semantic.prompt_block()))
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:8]
